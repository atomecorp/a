import fs from 'node:fs';
import path from 'node:path';

// Age-based residue retention. Every rule here only selects entries that no
// build, probe or session has used for the retention window, so it stays safe
// while compilers or the app run: an in-progress Cargo build has just read the
// fingerprints of every unit in its graph, and active work keeps fresh mtimes.
const DAY = 86_400_000;
export const residueRetentionDays = { cargo: 3, temp: 2, scratch: 2 };
const INCREMENTAL_CONFIGURATIONS_PER_CRATE = 2;
const INCREMENTAL_WRITE_GUARD = 2 * 3_600_000;

const HASHED = /-([0-9a-f]{16})(?:\.[A-Za-z0-9]+)?$/;
// Build trees, browser profiles and caches are regenerated by the probe that uses them.
const DISPOSABLE_DIRECTORY = /^(node_modules|target|build|DerivedData|dd|venv|\.venv|site-packages|__pycache__)$|(^|[_-])profile([_-]|\d|$)|cache$|[_-]build$|[_-]target$/i;
const KEPT_SOURCE = /\.(mjs|cjs|js|sh|py|swift|rb|md|json|txt)$/;
const KEPT_SOURCE_BYTES = 128 * 1024;
const RETAIN_MARKER = '.retain';

const entries = directory => fs.existsSync(directory) ? fs.readdirSync(directory, { withFileTypes: true }) : [];
const modifiedAt = stat => stat.mtimeMs;
const usedAt = stat => Math.max(stat.atimeMs, stat.mtimeMs);

// True as soon as one entry of the tree is newer than the cutoff.
function usedSince(file, cutoff, timeOf) {
    const stat = fs.lstatSync(file, { throwIfNoEntry: false });
    if (!stat) return false;
    if (timeOf(stat) >= cutoff) return true;
    if (!stat.isDirectory() || stat.isSymbolicLink()) return false;
    return entries(file).some(entry => usedSince(path.join(file, entry.name), cutoff, timeOf));
}

// Cargo target directories of the project, bounded and never inside staging copies.
function cargoTargets(root) {
    const targets = [];
    const visit = (directory, depth) => {
        for (const entry of entries(directory)) {
            if (!entry.isDirectory() || entry.name.startsWith('.') || entry.name === 'node_modules') continue;
            const child = path.join(directory, entry.name);
            if (entry.name === 'target' && fs.existsSync(path.join(child, 'CACHEDIR.TAG'))) targets.push(child);
            else if (depth > 0) visit(child, depth - 1);
        }
    };
    for (const base of ['platforms', 'atome']) visit(path.join(root, base), 4);
    return targets;
}

// Profiles are `target/<profile>` or `target/<triple>/<profile>`, recognized by Cargo's fingerprint store.
function cargoProfiles(target) {
    const profiles = [];
    for (const entry of entries(target)) {
        if (!entry.isDirectory()) continue;
        const child = path.join(target, entry.name);
        if (fs.existsSync(path.join(child, '.fingerprint'))) profiles.push(child);
        else for (const nested of entries(child)) {
            const profile = path.join(child, nested.name);
            if (nested.isDirectory() && fs.existsSync(path.join(profile, '.fingerprint'))) profiles.push(profile);
        }
    }
    return profiles;
}

// A Cargo unit (fingerprint, outputs and build-script directory share one hash)
// is removed whole, and only when none of its files was read or written in the
// window. Cargo rebuilds a removed unit if a later build needs it again.
function planCargoProfile(profile, cutoff, now, add) {
    const units = new Map();
    for (const store of ['.fingerprint', 'build', 'deps']) {
        for (const entry of entries(path.join(profile, store))) {
            const hash = HASHED.exec(entry.name)?.[1];
            if (!hash || entry.isSymbolicLink()) continue;
            const file = path.join(profile, store, entry.name);
            const unit = units.get(hash) || { used: false, files: [] };
            unit.used ||= usedSince(file, cutoff, usedAt);
            unit.files.push(file);
            units.set(hash, unit);
        }
    }
    for (const unit of units.values()) {
        if (!unit.used) unit.files.forEach(file => add(file, 'stale-cargo-unit'));
    }
    planIncremental(path.join(profile, 'incremental'), cutoff, now, add);
}

// rustc keeps one incremental directory per crate and build configuration, and
// alternating feature sets multiply them. Only the newest configurations of each
// crate are kept; a dropped one costs one non-incremental compile of that crate.
// Directories written recently may belong to a running rustc and are never touched.
function planIncremental(incremental, cutoff, now, add) {
    const byCrate = new Map();
    for (const entry of entries(incremental)) {
        if (!entry.isDirectory()) continue;
        const file = path.join(incremental, entry.name);
        const crate = entry.name.replace(/-[0-9a-z]+$/, '');
        byCrate.set(crate, [...(byCrate.get(crate) || []), { file, time: fs.statSync(file).mtimeMs }]);
    }
    for (const configurations of byCrate.values()) {
        configurations.sort((a, b) => b.time - a.time).forEach(({ file, time }, rank) => {
            if (time >= now - INCREMENTAL_WRITE_GUARD) return;
            if (rank >= INCREMENTAL_CONFIGURATIONS_PER_CRATE) add(file, 'superseded-incremental-cache');
            else if (!usedSince(file, cutoff, modifiedAt)) add(file, 'stale-incremental-cache');
        });
    }
}

// Keeps small reusable probe sources and `.retain`-marked folders; returns the disposable paths of a stale tree.
function disposableIn(file) {
    const stat = fs.lstatSync(file);
    if (stat.isSymbolicLink() || fs.existsSync(path.join(file, RETAIN_MARKER))) return { keeps: true, disposable: [] };
    if (!stat.isDirectory()) {
        const keeps = KEPT_SOURCE.test(file) && stat.size <= KEPT_SOURCE_BYTES;
        return { keeps, disposable: keeps ? [] : [file] };
    }
    if (DISPOSABLE_DIRECTORY.test(path.basename(file))) return { keeps: false, disposable: [file] };
    const children = entries(file).map(entry => disposableIn(path.join(file, entry.name)));
    if (!children.some(child => child.keeps)) return { keeps: false, disposable: [file] };
    return { keeps: true, disposable: children.flatMap(child => child.disposable) };
}

function planTemp(temp, cutoff, add) {
    for (const entry of entries(temp)) {
        const file = path.join(temp, entry.name);
        if (entry.isSymbolicLink() || usedSince(file, cutoff, modifiedAt)) continue;
        disposableIn(file).disposable.forEach(item => add(item, 'stale-temp-artifact', temp));
    }
}

function planScratch(scratch, cutoff, add) {
    for (const entry of entries(scratch)) {
        const session = path.join(scratch, entry.name);
        if (entry.isDirectory() && !usedSince(session, cutoff, modifiedAt)) add(session, 'stale-agent-scratchpad', scratch);
    }
}

// Xcode copies one symbol set per device model and OS build; only the newest is used.
function planDeviceSupport(deviceSupport, add) {
    const byModel = new Map();
    for (const entry of entries(deviceSupport)) {
        const model = /^(.+?) \d[\d.]* \([0-9A-Za-z]+\)$/.exec(entry.name)?.[1];
        if (!model || !entry.isDirectory()) continue;
        const file = path.join(deviceSupport, entry.name);
        byModel.set(model, [...(byModel.get(model) || []), { file, time: fs.statSync(file).mtimeMs }]);
    }
    for (const sets of byModel.values()) {
        sets.sort((a, b) => b.time - a.time).slice(1).forEach(set => add(set.file, 'superseded-device-symbols', deviceSupport));
    }
}

// CoreDevice keeps a copy of every build installed on a device (`devicectl install`, Xcode Run) as the base
// of the next delta install, and never drops one: 36 copies of the app, 23 GB by 26 Oct. 2026. Only the
// newest bases of the project's apps are used.
const INSTALL_BASES_PER_APP = 2;
function planInstallDeltas(installDeltas, add) {
    for (const app of entries(installDeltas)) {
        if (!app.isDirectory() || !app.name.startsWith('one.atome.')) continue;
        const directory = path.join(installDeltas, app.name);
        entries(directory).filter(entry => entry.isDirectory())
            .map(entry => ({ file: path.join(directory, entry.name), time: fs.statSync(path.join(directory, entry.name)).mtimeMs }))
            .sort((a, b) => b.time - a.time).slice(INSTALL_BASES_PER_APP)
            .forEach(base => add(base.file, 'superseded-device-install-base', installDeltas));
    }
}

// The probes' isolated Fastify servers (temp/comm/comm_harness.mjs) live in the system temp folders: a
// probe killed before its `stop` left its base and vault sockets behind (2 386 folders, 10 GB).
const PROBE_SERVER_FOLDERS = [{ name: /^comm-harness-/, base: 'systemTemp' }, { name: /^chv-/, base: 'tmp' }];
function planProbeServers(folders, cutoff, add) {
    for (const { name, base } of PROBE_SERVER_FOLDERS) {
        for (const entry of entries(folders[base])) {
            const file = path.join(folders[base], entry.name);
            if (entry.isDirectory() && name.test(entry.name) && !usedSince(file, cutoff, modifiedAt)) add(file, 'stale-probe-server', folders[base]);
        }
    }
}

export function planResidueCleanup({ root, now = Date.now(), days = residueRetentionDays, scratch, deviceSupport, installDeltas, probeServers }, add) {
    const cargoCutoff = now - days.cargo * DAY;
    for (const target of cargoTargets(root)) cargoProfiles(target).forEach(profile => planCargoProfile(profile, cargoCutoff, now, add));
    planTemp(path.join(root, 'temp'), now - days.temp * DAY, add);
    if (scratch) planScratch(scratch, now - days.scratch * DAY, add);
    if (deviceSupport) planDeviceSupport(deviceSupport, add);
    if (installDeltas) planInstallDeltas(installDeltas, add);
    if (probeServers) planProbeServers(probeServers, now - days.temp * DAY, add);
}
