// generated/index.md: the readable catalogue of the registry — where a thing is, what opens it, which command
// runs it. Built from the search index (paths) and the map (relations, annotations).
const cell = value => String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function indexMarkdown(map, search, report) {
    const entries = map.entries;
    const out = (from, type) => map.relations.filter(relation => relation.from === from && relation.type === type).map(relation => relation.to);
    const describe = (id) => {
        const entry = entries[id];
        const opens = entry.opens ? Object.entries(entry.opens).map(([key, value]) => `${key}: ${value}`).join('; ') : '';
        const runs = [...out(id, 'executes'), ...out(id, 'refers_to'), ...out(id, 'opens')].join(', ');
        const ref = entry.execution_ref ? `${entry.execution_ref.contract} ${JSON.stringify(entry.execution_ref.input)}` : '';
        return [opens, runs, ref].filter(Boolean).join(' · ');
    };
    const lines = ['# eVe registry catalogue', '',
        'Generated by `npm run registry:build` (scripts/registry/build_registry.mjs) from the real owners and `eVe/registry/source/*.json`. Do not edit.',
        `Design: eVe/documentations/global_registry_architecture.md. Inputs hash: \`${map.inputs_hash}\`.`, '',
        '## Counts', '', '| Kind | Entries |', '| --- | --- |',
        ...Object.entries(report.counts.by_kind).sort().map(([kind, total]) => `| ${kind} | ${total} |`), '',
        `Relations: ${report.counts.relations}; aliases: ${report.counts.aliases}; archived ids: ${report.counts.archived}. Holes and findings: generated/inventory-report.json.`, '',
        '## Where is it, what opens it', '',
        'Every placed node (Dashboard, menus) with its first path from a root. Visibility conditions: generated/ui-tree.json.', '',
        '| Label | Id | Key | Path | Opens / runs |', '| --- | --- | --- | --- | --- |'];
    const firstById = new Map();
    search.forEach(item => { if (!firstById.has(item.id)) firstById.set(item.id, item); });
    for (const item of [...firstById.values()].sort((a, b) => (a.path.join('/') < b.path.join('/') ? -1 : 1))) {
        lines.push(`| ${cell(item.label)} | \`${item.id}\` | ${cell(item.key)} | ${cell(item.path.slice(0, -1).map(id => entries[id]?.native_id || id).join(' › '))} | ${cell(describe(item.id))} |`);
    }
    lines.push('', '## Commands (contract families and MCP methods)', '', '| Family | Commands | Risk tiers | Offline |', '| --- | --- | --- | --- |');
    const families = new Map();
    Object.values(entries).filter(entry => entry.kind === 'action_contract').forEach(entry => {
        const key = `${entry.surface}:${entry.family}`;
        if (!families.has(key)) families.set(key, { total: 0, tiers: new Set(), offline: new Set() });
        const family = families.get(key); family.total += 1; family.tiers.add(entry.risk_tier); family.offline.add(entry.offline);
    });
    [...families].sort().forEach(([key, family]) => lines.push(`| ${key} | ${family.total} | ${[...family.tiers].sort().join(', ')} | ${[...family.offline].sort().join(', ')} |`));
    lines.push('', '## Aliases', '', '| Alias | Canonical id | Status |', '| --- | --- | --- |',
        ...Object.entries(map.aliases).map(([alias, target]) => `| ${cell(alias)} | \`${target.target}\` | ${target.status} |`), '');
    return lines.join('\n');
}
