// The tools an MCP caller may call, one entry per name: the business methods of the single entry
// (mail, contacts, calendar, bank, conditions, the contract commands), then the Runtime V2 tools,
// then the assistant's tools. Each carries the policy the entry will apply to it, and the list is
// the transport actor's: a tool its capabilities or sandbox refuse is not offered. Input schemas are the live
// owners' (contracts, runtime records, gateway parameters); words and risk tiers are the registry's.
import { MCP_ERROR, cloneValue, mcpError } from './mcp_core.js';
import { ensureRuntimeToolApi, loadAIAgent } from './mcp_bridges.js';
import { resolveAccessPolicy } from './mcp_security_policy.js';
import { hasActorCapability, hasSandboxProfile } from './mcp_security.js';
import { findContractCommand } from './mcp_contract_families.js';
import { PERSONAL_IMPORT_TOOLS } from '#shared/personal_import_tools.js';
import { RISK_TIERS } from '../ai/agent_gateway_state.js';

// Methods of the entry that are its own machinery, not tools.
const INFRASTRUCTURE_METHOD = /^(mcp\.|runtime\.|ai\.|atome\.describe$)/;
const OPEN_SCHEMA = Object.freeze({ type: 'object', additionalProperties: true });

// What discovery says of a tool (its words, title and risk tier) is the registry's (eVe/registry, generated by
// `npm run registry:build` from the tools' owners): one entry per tool, by its exact id. A tool with no entry, or an
// entry with no tier, is an error of the registry (registry:check requires a tier on every tool and command).
const REGISTRY_ID = Object.freeze({
    method: name => `action_contract:${name}`,
    runtime: name => `tool_definition:${name}`,
    ai: name => `tool_definition:ai_tool:${name}`
});
const registryWords = (registry, source, name) => {
    const entry = registry.definitionOf(REGISTRY_ID[source](name));
    if (!entry) throw mcpError(MCP_ERROR.INTERNAL, `mcp_tool_unregistered:${REGISTRY_ID[source](name)}`);
    if (!RISK_TIERS.includes(entry.risk_tier)) throw mcpError(MCP_ERROR.INTERNAL, `mcp_tool_risk_tier_missing:${entry.id}`);
    return { ...(entry.label && entry.label !== name ? { title: entry.label } : {}), ...(entry.description ? { description: entry.description } : {}),
        risk_tier: entry.risk_tier };
};

const methodSchema = (name) => {
    const contract = findContractCommand(name);
    if (contract) return cloneValue(contract.input_schema);
    const imported = PERSONAL_IMPORT_TOOLS.find(tool => tool.name === name);
    return imported ? { type: 'object', properties: cloneValue(imported.properties || {}) } : OPEN_SCHEMA;
};

export async function listUnifiedMcpTools(actor, handlers) {
    const { registry } = await import('../../../../eVe/registry/registry_runtime.js');
    const tools = new Map();
    const add = (entry) => { if (entry.name && !tools.has(entry.name)) tools.set(entry.name, { ...entry, ...registryWords(registry, entry.source, entry.name) }); };
    Object.keys(handlers).filter(name => !INFRASTRUCTURE_METHOD.test(name)).forEach((name) => {
        add({ name, inputSchema: methodSchema(name), source: 'method', policy: resolveAccessPolicy(name, {}) });
    });
    const runtime = ensureRuntimeToolApi();
    for (const entry of await runtime.listTools({ includeDisabled: false })) {
        const name = String(entry?.id || '').trim();
        add({ name, inputSchema: cloneValue(entry?.input_schema || OPEN_SCHEMA), ...(entry?.output_schema ? { outputSchema: cloneValue(entry.output_schema) } : {}),
            source: 'runtime', policy: resolveAccessPolicy('runtime.tools.call', { tool_id: name }) });
    }
    const agent = await loadAIAgent();
    for (const entry of agent.listTools()) {
        add({ name: entry.name, inputSchema: cloneValue(entry.parameters || OPEN_SCHEMA), source: 'ai',
            policy: resolveAccessPolicy('ai.tools.call', { tool_name: entry.name }, { aiTool: entry }) });
    }
    return [...tools.values()].filter(entry => entry.policy.allowed === true
        && hasActorCapability(actor, entry.policy.required_capabilities) && hasSandboxProfile(actor, entry.policy.sandbox_profile))
        .map(({ policy, ...entry }) => ({ ...entry, confirmation_required: policy.confirmation_required === true }));
}
